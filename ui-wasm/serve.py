#!/usr/bin/env python3
"""Static file server for the built browser UI, serving the current working
directory on 127.0.0.1.

Exists only because `python3 -m http.server` cannot send a header, and the one
missing header costs an afternoon. http.server sends `Last-Modified` but no
`ETag` and no `Cache-Control`, so a browser is free to apply heuristic
freshness: with no explicit lifetime it may reuse a cached copy for a while
without asking the server anything at all.

That is a trap for a Qt wasm bundle specifically. The 250K `.js` glue and the
25M `.wasm` are one artifact in two files - the `EM_ASM` table in the glue is
addressed by offsets baked into the module - and the glue keeps the same size
across rebuilds. So a reload can pair yesterday's glue with today's module,
and the browser reports:

    WebAssembly.instantiate(): Import #0 "env": module is not an object or
        function
    ASM_CONSTS[code] is not a function

Neither names a cache, both read as a broken build, and the bundle on disk is
fine. On 2026-10-18 this was diagnosed three times over - a real mid-relink
bundle, then a stale-loader theory that turned out false, then the cache -
before being fixed here.

`no-cache` is the fix and does not mean "do not store": it means revalidate
before reuse. The conditional request still gets a 304 from the
`If-Modified-Since` handling in SimpleHTTPRequestHandler, so an unchanged 25M
`.wasm` is not re-downloaded - it is only re-checked. Which is what makes a
fixed port safe to keep.
"""

import http.server
import os
import sys

MODULE = "nixdash_ui_wasm_app.wasm"

# Injected into the served page, so a finished build reloads the tab you
# already have open - and says so in the console, which is the point: the
# browser is the one place this app's QML errors are visible at all (Qt's
# stderr is bound to console.error by the generated glue), so the console is
# already open while working on the browser UI. A reload that announces itself
# there turns "did the build finish?" into something you can see.
#
# Injected at serve time rather than edited into the page, because
# nixdash_ui_wasm_app.html is copied read-only (444) from the Qt store path
# and is regenerated by the build. Nothing generated is touched.
#
# HEAD on the module, not the page: the .wasm is the artifact whose mtime
# moves when a build lands, and a HEAD costs no transfer of its 25M.
RELOAD_SNIPPET = """
<script>
(function () {
  var known = null;
  function check() {
    fetch("%s", { method: "HEAD", cache: "no-store" }).then(function (r) {
      var stamp = r.headers.get("last-modified");
      if (!stamp) return;
      if (known === null) {
        known = stamp;
        console.log("[nixdash] watching the build, served " + stamp);
        return;
      }
      if (stamp !== known) {
        console.log("[nixdash] new build served " + stamp + " - reloading");
        location.reload();
      }
    }).catch(function () { /* server stopped; keep polling */ });
  }
  setInterval(check, 2000);
  check();
})();
</script>
""" % MODULE


class RevalidateHandler(http.server.SimpleHTTPRequestHandler):
    """SimpleHTTPRequestHandler, but every response must be revalidated, and
    HTML carries the reload poller."""

    # Set by --quiet: drop the poller's own requests from the log, so this can
    # share a pane with `just watch-browser` without burying its build
    # reports. The poller is the bulk of the traffic by far - one HEAD every
    # two seconds while the tab is focused - and it says nothing a reader
    # wants. Real fetches still print, so "the page loaded" remains visible.
    quiet_poller = False

    def end_headers(self):
        # Belongs on every response, including the 304s.
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()

    def log_message(self, fmt, *args):
        if self.quiet_poller and self.command == "HEAD" and self.path.endswith(".wasm"):
            return
        super().log_message(fmt, *args)

    # How far apart the glue and the module may be and still be one build.
    # They are written seconds apart by the same link step; eleven MINUTES
    # apart is what two interleaved builds looked like.
    PAIR_TOLERANCE = 60

    def _mixed_bundle(self):
        """-> a sentence when the glue and the module are not one build.

        A tripwire, not a mechanism: build.sh publishes the three files as a
        set and flips a symlink, so this should never fire. It exists because
        the failure it catches is unreadable from the browser - the console
        says `Import #0 "env": module is not an object or function`, which
        sent an afternoon looking for a broken build rather than two halves
        of different ones. If this ever fires, something is writing into the
        served tree again.
        """
        here = os.path.dirname(self.translate_path("/"))
        try:
            js = os.path.getmtime(os.path.join(here, "nixdash_ui_wasm_app.js"))
            wasm = os.path.getmtime(os.path.join(here, "nixdash_ui_wasm_app.wasm"))
        except OSError:
            return None
        gap = abs(js - wasm)
        if gap <= self.PAIR_TOLERANCE:
            return None
        return (
            "The glue and the module on disk are %d minutes apart, so they are "
            "two different builds. Loading them would fail with "
            "'Import #0 \"env\"' - which reads as a broken build and is not "
            "one. Rebuild: ./build.sh" % round(gap / 60)
        )

    def _page(self):
        """The requested page with the poller in it, or None if this request
        is not for a page.

        Only the page is rewritten; everything else - the glue, the module,
        the logo - is served untouched by the parent class, which keeps its
        If-Modified-Since handling and therefore the 304s.
        """
        path = self.translate_path(self.path)
        if os.path.isdir(path):
            path = os.path.join(path, "index.html")
        if not (path.endswith(".html") and os.path.isfile(path)):
            return None

        mixed = self._mixed_bundle()
        if mixed is not None:
            return (
                "<!doctype html><meta charset=utf-8>"
                "<title>nixdash - mixed bundle</title>"
                "<body style='font:14px monospace;padding:2em;max-width:46em'>"
                "<h1 style='font-size:1.2em'>Two builds, not one</h1>"
                "<p>" + mixed + "</p></body>"
            ).encode()

        with open(path, "rb") as fh:
            body = fh.read()
        marker = b"</body>"
        snippet = RELOAD_SNIPPET.encode()
        return (
            body.replace(marker, snippet + marker, 1)
            if marker in body
            else body + snippet
        )

    def _send_page_headers(self, body):
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()

    def do_GET(self):
        body = self._page()
        if body is None:
            return super().do_GET()
        self._send_page_headers(body)
        self.wfile.write(body)

    def do_HEAD(self):
        # Shares one body with do_GET, so the advertised length is the length
        # that would be delivered. Overriding only GET left HEAD reporting the
        # file's size on disk, 650 bytes short of the injected page.
        body = self._page()
        if body is None:
            return super().do_HEAD()
        self._send_page_headers(body)


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--quiet"]
    RevalidateHandler.quiet_poller = "--quiet" in sys.argv[1:]
    port = int(args[0]) if args else 8099

    # Threading, because the page fetches the glue and the module at once and
    # the module is 25M: a single-threaded server makes them queue.
    server = http.server.ThreadingHTTPServer(("127.0.0.1", port), RevalidateHandler)
    print(f"http://127.0.0.1:{port}/", flush=True)
    print("(the engine must also be running: cargo run -p nixdash-engine)", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
